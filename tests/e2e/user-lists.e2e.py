import sys
from harness import *
import harness
R = []
def check(n, c, d=""): R.append(bool(c)); print(("PASS " if c else "FAIL ") + n + ((" :: " + str(d)) if d and not c else ""))
def main(page, out):
    t = lambda sel: page.inner_text(sel)
    cards = lambda: page.locator("#user .umcards .lcard:not(.skel)").count()
    page.click('#tabs [data-v="profile"]'); page.wait_for_function("document.querySelector('#pcFollowers').textContent !== '\u2013'")
    page.click("#pcFollowersBtn"); page.wait_for_selector("#user .ucard")
    page.click("#user .ucard:nth-child(1) .uname"); page.wait_for_selector("#user .pcard .pname")
    page.wait_for_function("[...document.querySelectorAll('#user .pcounts b')][3].textContent !== '\u2013'")
    check("on a profile, the Anime and Manga counts are buttons", page.locator('#user .pcounts button:has-text("Anime")').count() == 1 and page.locator('#user .pcounts button:has-text("Manga")').count() == 1)
    page.click('#user .pcounts button:has-text("Anime")'); page.wait_for_selector("#user .umcards .lcard:not(.skel)", timeout=15000)
    check("their list opens with whose list it is", "Moreaumi" in t("#user .utop"), t("#user .utop"))
    n = cards()
    check("the first 24 titles show", n == 24, n)
    check("it is read-only: no +1 buttons", page.locator("#user .umcards .lplus").count() == 0)
    chips = page.evaluate("[...document.querySelectorAll('#user .umstat .chip')].map(c => c.textContent)")
    check("status chips start with All and a count", len(chips) >= 2 and chips[0].startswith("All") and chips[0][3:].isdigit(), chips)
    first = page.evaluate("document.querySelector('#user .umcards .lcard .lt').textContent")
    page.fill("#user .umsearch", first[:5]); page.wait_for_timeout(200)
    m = cards()
    check("search narrows the list", 1 <= m <= n, (first[:5], m))
    page.fill("#user .umsearch", "zzzzqq"); page.wait_for_timeout(200)
    check("a search with no match says so", cards() == 0 and "No titles match" in t("#user .msg"))
    page.fill("#user .umsearch", ""); page.wait_for_timeout(200)
    page.click('#user button:has-text("Show more")'); page.wait_for_timeout(200)
    check("Show more adds the next 24", cards() == 48, cards())
    page.click('#user .umstat .chip:nth-child(2)'); page.wait_for_timeout(200)
    check("a status chip shows only that status", 0 < cards() <= 48 and page.get_attribute('#user .umstat .chip:nth-child(2)', "aria-pressed") == "true")
    page.click('#user .umsort .chip:has-text("Score")'); page.wait_for_timeout(200)
    check("the Score sort button is marked", page.get_attribute('#user .umsort .chip:has-text("Score")', "aria-pressed") == "true")
    page.click('#user .umtypes .chip:has-text("Manga")'); page.wait_for_selector("#user .umcards .lcard:not(.skel)", timeout=15000)
    check("Manga switches to their manga list", page.get_attribute('#user .umtypes .chip:has-text("Manga")', "aria-pressed") == "true" and cards() > 0)
    # a title opens above the people screens and closes back to the list
    page.click("#user .umcards .lcard .lmain >> nth=0"); page.wait_for_selector("#media:not([hidden])", timeout=15000)
    check("the title page shows above the person's list", page.evaluate("(() => { const r = document.querySelector('#media').getBoundingClientRect(), e = document.elementFromPoint(r.left + r.width / 2, r.top + 90); return !!e && !!e.closest('#media'); })()"))
    page.evaluate("closeMedia()"); page.wait_for_timeout(300)
    check("closing the title returns to the list, not the profile", page.locator("#media").is_hidden() and page.locator("#user .umcards").is_visible())
    page.click("#user .uback"); page.wait_for_selector("#user .pcard .pname")
    check("back goes to their profile", "Moreaumi" in t("#user .pname"))
    check("narrow width: nothing sticks out sideways", page.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1"))
out = run(main, viewport=(360, 780))
real = [c for c in out["console"] if "ERR_INTERNET" not in c[1]]
check("no console errors", not real and not out["errors"], (real[:2], out["errors"][:2]))
print("%d checks, %d failed" % (len(R), R.count(False))); sys.exit(1 if False in R else 0)
